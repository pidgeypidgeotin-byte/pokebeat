export const FIRST_151: PokedexEntry[] = NAMES.map((name, index) => ({
  id: index + 1,
  name,
  sprite: PMD_SPRITES[index + 1] ?? `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${index + 1}.png`,
  spriteSource: PMD_SPRITES[index + 1] ? "PMD SpriteCollab" : "PokeAPI fallback",
}));

export function getPokedexEntry(species: string | number) {
  if (typeof species === "number") return FIRST_151[species - 1] ?? FIRST_151[24];
  return FIRST_151.find((entry) => entry.name.toLowerCase() === species.toLowerCase()) ?? FIRST_151[24];
}
